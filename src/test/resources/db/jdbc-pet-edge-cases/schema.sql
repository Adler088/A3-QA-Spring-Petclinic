-- PQT-7: minimal H2 schema that mirrors db/postgres/schema.sql, where pets.owner_id is NULLABLE.
-- Used only by JdbcPetRepositoryImplTests to exercise pets without owner on the JDBC repositories.
CREATE TABLE types (
  id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80)
);

CREATE TABLE owners (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name VARCHAR(30),
  last_name  VARCHAR(30),
  address    VARCHAR(255),
  city       VARCHAR(80),
  telephone  VARCHAR(20)
);

CREATE TABLE pets (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(30),
  birth_date DATE,
  type_id    INTEGER NOT NULL REFERENCES types (id),
  owner_id   INTEGER REFERENCES owners (id)
);

CREATE TABLE visits (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id      INTEGER REFERENCES pets (id),
  visit_date  DATE,
  description VARCHAR(255)
);
